func TestDeletePhotoshootWithHistory(t *testing.T) {
	ctx := context.Background()
	e := newEnv(t, 0, "")
	e.start()

	g := e.waitStatus(e.generate("tryon", 2).ID, StatusSucceeded)
	e.review(g.Images[0], "rejected", "fidelity")
	e.review(g.Images[0], "approved", "") // two events
	steps, _ := e.svc.GetGeneration(ctx, g.ID)
	var stepOutputs []string
	for _, st := range steps.Steps {
		stepOutputs = append(stepOutputs, st.OutputHash)
	}

	// The product's photograph is deleted, but the generation still keeps
	// its bytes alive.
	prod, _ := e.cat.GetProduct(ctx, e.product.ID)
	front := prod.Images[0]
	if err := e.cat.DeleteProductImage(ctx, prod.ID, front.ID); err != nil {
		t.Fatal(err)
	}

	// Review history stays append-only outside a deliberate deletion.
	if _, err := e.db.Write.ExecContext(ctx, `DELETE FROM review_event`); err == nil || !strings.Contains(err.Error(), "append-only") {
		t.Fatalf("review history deleted directly: %v", err)
	}

	del, err := e.svc.DeletePhotoshoot(ctx, e.shoot.ID)
	if err != nil {
		t.Fatal(err)
	}
	if del.Generations != 1 || del.Images != 2 {
		t.Fatalf("deleted: %+v", del)
	}
	if _, err := e.svc.GetPhotoshoot(ctx, e.shoot.ID); !errors.Is(err, ErrNotFound) {
		t.Fatalf("photoshoot kept: %v", err)
	}
	if _, err := e.svc.GetGeneration(ctx, g.ID); !errors.Is(err, ErrNotFound) {
		t.Fatalf("generation kept: %v", err)
	}
	if _, err := e.svc.GetImage(ctx, g.Images[0].ID); !errors.Is(err, ErrNotFound) {
		t.Fatalf("image kept: %v", err)
	}
	for _, h := range append([]string{g.Images[0].Hash, g.Images[1].Hash}, stepOutputs...) {
		if _, err := e.blobs.Open(ctx, blob.Generated, h); !errors.Is(err, blob.ErrNotFound) {
			t.Fatalf("generated bytes kept: %s %v", h, err)
		}
	}
	// The input only the generation used is gone; the model's photograph,
	// still in use, is kept.
	if _, err := e.blobs.Open(ctx, blob.Original, front.Hash); !errors.Is(err, blob.ErrNotFound) {
		t.Fatalf("orphaned input kept: %v", err)
	}
	model, _ := e.cat.GetModel(ctx, e.model.ID)
	if o, err := e.blobs.Open(ctx, blob.Original, model.Images[0].Hash); err != nil {
		t.Fatalf("model photograph removed: %v", err)
	} else {
		_ = o.Close()
	}
	var guard int
	_ = e.db.Read.QueryRowContext(ctx, `SELECT count(*) FROM purge_guard`).Scan(&guard)
	if guard != 0 {
		t.Fatal("purge guard left behind")
	}

	// The work no longer counts, and the product can now be deleted.
	if sum, _ := e.svc.MetricsSummary(ctx, MetricsFilter{}); sum.Total.Generations != 0 {
		t.Fatalf("metrics: %+v", sum.Total)
	}
	if err := e.cat.DeleteProduct(ctx, e.product.ID); err != nil {
		t.Fatalf("delete product: %v", err)
	}
	if _, err := e.svc.DeletePhotoshoot(ctx, e.shoot.ID); !errors.Is(err, ErrNotFound) {
		t.Fatalf("second delete: %v", err)
	}
}

func TestDeletePhotoshootRefusedWhileRunning(t *testing.T) {
	ctx := context.Background()
	e := newEnv(t, time.Hour, "")
	e.start()
	g := e.waitStatus(e.generate("reference", 1).ID, StatusRunning)

	var ce *ConflictError
	if _, err := e.svc.DeletePhotoshoot(ctx, e.shoot.ID); !errors.As(err, &ce) || !strings.Contains(ce.Reason, "still running") {
		t.Fatalf("running: %v", err)
	}
	if _, err := e.svc.CancelGeneration(ctx, g.ID); err != nil {
		t.Fatal(err)
	}
	e.waitStatus(g.ID, StatusCancelled)
	if _, err := e.svc.DeletePhotoshoot(ctx, e.shoot.ID); err != nil {
		t.Fatalf("after cancel: %v", err)
	}
}
