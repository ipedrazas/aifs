func fixture(t *testing.T, name string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("..", "imaging", "testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func ptr[T any](v T) *T { return &v }

var fastRunner = RunnerConfig{
	Workers: 2, ProviderConcurrency: 4, PollInterval: 5 * time.Millisecond, ScanInterval: 20 * time.Millisecond,
	StepTimeout: 5 * time.Second, MaxAttempts: 3, RetryBase: time.Millisecond,
}

func newEnv(t *testing.T, fakeDelay time.Duration, instructions string) *env {
	t.Helper()
	ctx := context.Background()
	dir := t.TempDir()
	d, err := db.Open(ctx, dir)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = d.Close() })
	store, err := blob.NewFS(filepath.Join(dir, "blobs"))
	if err != nil {
		t.Fatal(err)
	}
	log := slog.New(slog.NewTextHandler(io.Discard, nil))
	e := &env{t: t, db: d, blobs: store, log: log}
	e.cat = catalog.New(d, store, log)
	e.reg = provider.NewRegistry()
	e.reg.Add(fake.New(fakeDelay), 0)
	e.runner = NewRunner(d, store, e.reg, log, fastRunner)
	e.svc = New(d, store, e.cat, e.reg, e.runner, log, Config{MaxVariations: 4})

	e.product, _ = e.cat.CreateProduct(ctx, catalog.ProductInput{Name: ptr("Slim jeans"), Colour: ptr("indigo"), PrintDetails: ptr("embroidered pocket")})
	if _, err := e.cat.AddProductImage(ctx, e.product.ID, "front", "f.png", fixture(t, "plain.png")); err != nil {
		t.Fatal(err)
	}
	if _, err := e.cat.AddProductImage(ctx, e.product.ID, "back", "b.webp", fixture(t, "plain.webp")); err != nil {
		t.Fatal(err)
	}
	e.model, _ = e.cat.CreateModel(ctx, catalog.ModelInput{Name: ptr("Ava"), Appearance: ptr("tall")})
	if _, err := e.cat.AddModelImage(ctx, e.model.ID, "identity", "a.jpg", fixture(t, "rot6.jpg")); err != nil {
		t.Fatal(err)
	}
	e.shoot, err = e.svc.CreatePhotoshoot(ctx, PhotoshootInput{
		ProductID: &e.product.ID, ModelID: &e.model.ID, CustomInstructions: ptr(instructions),
	})
	if err != nil {
		t.Fatal(err)
	}
	return e
}

func (e *env) start() {
	ctx, cancel := context.WithCancel(context.Background())
	e.stop = cancel
	e.done = make(chan struct{})
	go func() { e.runner.Run(ctx); close(e.done) }()
	e.t.Cleanup(e.shutdown)
}

func (e *env) shutdown() {
	if e.stop != nil {
		e.stop()
		<-e.done
		e.stop = nil
	}
}

func (e *env) generate(recipe string, variations int) Generation {
	e.t.Helper()
	g, err := e.svc.StartGeneration(context.Background(), e.shoot.ID, GenerationRequest{Recipe: recipe, Provider: fake.Name, Variations: variations})
	if err != nil {
		e.t.Fatal(err)
	}
	return g
}

func (e *env) waitStatus(id int64, statuses ...string) Generation {
	e.t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for {
		g, err := e.svc.GetGeneration(context.Background(), id)
		if err != nil {
			e.t.Fatal(err)
		}
		for _, s := range statuses {
			if g.Status == s {
				return g
			}
		}
		if time.Now().After(deadline) {
			e.t.Fatalf("generation %d stuck in %s (want %v): %+v", id, g.Status, statuses, g.Steps)
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func TestReferenceRecipeEndToEnd(t *testing.T) {
	e := newEnv(t, 0, "")
	e.start()
	g := e.generate("reference", 3)
	// The runner may already have claimed it by the time it is read back.
	if (g.Status != StatusQueued && g.Status != StatusRunning) || len(g.Steps) != 3 || g.StepsTotal != 3 {
		t.Fatalf("queued: %+v", g)
	}

	g = e.waitStatus(g.ID, StatusSucceeded)
	if len(g.Images) != 3 || g.CostMicros != 3*fake.CostMicros || g.Error != "" || g.FinishedAt == nil {
		t.Fatalf("finished: %+v", g)
	}
	seen := map[string]bool{}
	for _, im := range g.Images {
		if im.ReviewStatus != "pending" || im.Product.ID != e.product.ID || im.Model.ID != e.model.ID || im.Recipe != "reference" || im.Provider != fake.Name {
			t.Fatalf("image: %+v", im)
		}
		seen[im.Hash] = true
		o, err := e.blobs.Open(context.Background(), blob.Generated, im.Hash)
		if err != nil {
			t.Fatalf("generated bytes: %v", err)
		}
		_ = o.Close()
	}
	if len(seen) != 3 {
		t.Fatal("variations are not distinct")
	}

	// The snapshot records everything that produced the images.
	s := g.Settings
	if s.Recipe != "reference" || s.Provider != fake.Name || s.Variations != 3 || s.AspectRatio != "3:4" ||
		s.Product.Name != "Slim jeans" || s.Model.Appearance != "tall" || len(s.Steps) != 1 || len(s.Inputs) != 3 {
		t.Fatalf("snapshot: %+v", s)
	}
	if s.Steps[0].ProviderModel != "fake-reference_generate-v1" || len(s.Steps[0].Inputs) != 3 {
		t.Fatalf("step snapshot: %+v", s.Steps[0])
	}
	if s.Inputs[0].Role != "garment" || s.Inputs[0].Label != "front" || s.Inputs[2].Role != "model" {
		t.Fatalf("inputs: %+v", s.Inputs)
	}
	if !strings.Contains(g.Prompt, "embroidered pocket") || !strings.Contains(g.Prompt, "Reproduce the garment exactly") {
		t.Fatalf("prompt: %s", g.Prompt)
	}

	detail, err := e.svc.GetImage(context.Background(), g.Images[0].ID)
	if err != nil || detail.Settings.Recipe != "reference" || len(detail.Steps) != 1 || detail.CostMicros != fake.CostMicros {
		t.Fatalf("image detail: %+v %v", detail, err)
	}
}

func TestTryOnRecipeChainsSteps(t *testing.T) {
	e := newEnv(t, 0, "")
	e.start()
	g := e.waitStatus(e.generate("tryon", 2).ID, StatusSucceeded)
	if len(g.Images) != 2 || len(g.Steps) != 4 {
		t.Fatalf("tryon: %+v", g)
	}
	for _, st := range g.Steps {
		if st.Status != StepSucceeded || st.OutputHash == "" {
			t.Fatalf("step: %+v", st)
		}
	}
	// The try-on step got only the front garment image.
	if got := g.Settings.Steps[1]; got.Capability != "try_on" || !got.UsesPrevious || len(got.Inputs) != 1 {
		t.Fatalf("try-on step: %+v", got)
	}
	// The image is the output of the last step.
	byVariation := map[int]string{}
	for _, st := range g.Steps {
		if st.Position == 2 {
			byVariation[st.Variation] = st.OutputHash
		}
	}
	for _, im := range g.Images {
		if im.Hash != byVariation[im.Variation] {
			t.Fatalf("image %d is not the try-on output", im.ID)
		}
	}
}

