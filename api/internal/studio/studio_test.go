func TestUsedRecordsAreKept(t *testing.T) {
	ctx := context.Background()
	e := newEnv(t, 0, "")
	e.start()
	g := e.waitStatus(e.generate("reference", 1).ID, StatusSucceeded)

	// The model is archived, not deleted.
	deleted, err := e.cat.DeleteModel(ctx, e.model.ID)
	if err != nil || deleted {
		t.Fatalf("delete used model: deleted=%v err=%v", deleted, err)
	}
	// An archived model cannot start new work.
	var ve *ValidationError
	if _, err := e.svc.StartGeneration(ctx, e.shoot.ID, GenerationRequest{Recipe: "reference", Provider: fake.Name, Variations: 1}); !errors.As(err, &ve) {
		t.Fatalf("archived model accepted: %v", err)
	}

	// Deleting a reference photograph keeps the bytes the generation used.
	prod, _ := e.cat.GetProduct(ctx, e.product.ID)
	if err := e.cat.DeleteProductImage(ctx, prod.ID, prod.Images[0].ID); err != nil {
		t.Fatal(err)
	}
	if o, err := e.blobs.Open(ctx, blob.Original, g.Settings.Inputs[0].Hash); err != nil {
		t.Fatalf("input bytes removed: %v", err)
	} else {
		_ = o.Close()
	}

	// A photoshoot with generations cannot be deleted; an unused one can.
	var ce *ConflictError
	if err := e.svc.DeletePhotoshoot(ctx, e.shoot.ID); !errors.As(err, &ce) {
		t.Fatalf("delete used photoshoot: %v", err)
	}

	// The snapshot cannot be rewritten.
	if _, err := e.db.Write.ExecContext(ctx, `UPDATE generation SET prompt = 'x' WHERE id = ?`, g.ID); err == nil ||
		!strings.Contains(err.Error(), "immutable") {
		t.Fatalf("snapshot rewritten: %v", err)
	}
}

func TestPhotoshootCRUD(t *testing.T) {
	ctx := context.Background()
	e := newEnv(t, 0, "")
	if e.shoot.Name != "Slim jeans on Ava" || e.shoot.AspectRatio != "3:4" || e.shoot.Product.CoverHash == "" || e.shoot.Model.CoverHash == "" {
		t.Fatalf("defaults: %+v", e.shoot)
	}
	up, err := e.svc.UpdatePhotoshoot(ctx, e.shoot.ID, PhotoshootInput{AspectRatio: ptr("1:1"), CustomInstructions: ptr("hands in pockets")})
	if err != nil || up.AspectRatio != "1:1" || up.CustomInstructions != "hands in pockets" {
		t.Fatalf("update: %+v %v", up, err)
	}
	var ve *ValidationError
	if _, err := e.svc.UpdatePhotoshoot(ctx, e.shoot.ID, PhotoshootInput{AspectRatio: ptr("5:7")}); !errors.As(err, &ve) {
		t.Fatalf("bad ratio: %v", err)
	}
	if _, err := e.svc.CreatePhotoshoot(ctx, PhotoshootInput{ProductID: &e.product.ID}); !errors.As(err, &ve) {
		t.Fatalf("missing model: %v", err)
	}
	if _, err := e.svc.CreatePhotoshoot(ctx, PhotoshootInput{ProductID: ptr(int64(999)), ModelID: &e.model.ID}); !errors.As(err, &ve) {
		t.Fatalf("missing product: %v", err)
	}

	list, _ := e.svc.ListPhotoshoots(ctx, e.product.ID)
	if len(list) != 1 {
		t.Fatalf("list: %+v", list)
	}
	if err := e.svc.DeletePhotoshoot(ctx, e.shoot.ID); err != nil {
		t.Fatalf("delete unused: %v", err)
	}
}
