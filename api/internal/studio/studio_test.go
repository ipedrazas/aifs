func TestRestartResumesWithoutLossOrDuplicates(t *testing.T) {
	e := newEnv(t, 300*time.Millisecond, "")
	e.start()
	g := e.generate("reference", 3)

	// Wait until every step has been submitted, then stop the server.
	deadline := time.Now().Add(5 * time.Second)
	for {
		cur, _ := e.svc.GetGeneration(context.Background(), g.ID)
		submitted := 0
		for _, st := range cur.Steps {
			if st.Status == StepSubmitted {
				submitted++
			}
		}
		if submitted == 3 {
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("steps never submitted: %+v", cur.Steps)
		}
		time.Sleep(5 * time.Millisecond)
	}
	e.shutdown()

	cur, _ := e.svc.GetGeneration(context.Background(), g.ID)
	if cur.Status != StatusRunning {
		t.Fatalf("shutdown changed the status to %s", cur.Status)
	}

	// A new process: fresh provider (the in-memory jobs are gone, as if the
	// provider forgot them) and a fresh runner.
	e.reg = provider.NewRegistry()
	e.reg.Add(fake.New(0), 0)
	e.runner = NewRunner(e.db, e.blobs, e.reg, e.log, fastRunner)
	e.svc = New(e.db, e.blobs, e.cat, e.reg, e.runner, e.log, Config{MaxVariations: 4})
	e.start()

	done := e.waitStatus(g.ID, StatusSucceeded)
	if len(done.Images) != 3 {
		t.Fatalf("images after resume: %d", len(done.Images))
	}
	var n int
	_ = e.db.Read.QueryRow(`SELECT count(*) FROM generated_image WHERE generation_id = ?`, g.ID).Scan(&n)
	if n != 3 {
		t.Fatalf("duplicates: %d images", n)
	}
	for _, st := range done.Steps {
		if st.Attempts != 2 {
			t.Fatalf("expected one resubmission per lost job: %+v", st)
		}
	}
}

