func TestCancelQueued(t *testing.T) {
	e := newEnv(t, 0, "") // runner not started: stays queued
	g := e.generate("reference", 2)
	got, err := e.svc.CancelGeneration(context.Background(), g.ID)
	if err != nil || got.Status != StatusCancelled {
		t.Fatalf("cancel: %+v %v", got, err)
	}
	for _, st := range got.Steps {
		if st.Status != StepCancelled {
			t.Fatalf("step: %+v", st)
		}
	}
	// The runner does not pick it up later.
	e.start()
	time.Sleep(60 * time.Millisecond)
	if again, _ := e.svc.GetGeneration(context.Background(), g.ID); again.Status != StatusCancelled {
		t.Fatalf("status: %s", again.Status)
	}

	var ce *ConflictError
	if _, err := e.svc.CancelGeneration(context.Background(), g.ID); !errors.As(err, &ce) {
		t.Fatalf("second cancel: %v", err)
	}
	if _, err := e.svc.CancelGeneration(context.Background(), 999); !errors.Is(err, ErrNotFound) {
		t.Fatalf("missing: %v", err)
	}
}

