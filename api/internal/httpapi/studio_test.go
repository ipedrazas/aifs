// shootFixture creates a product and a model with images and a photoshoot.
func shootFixture(t *testing.T, h http.Handler, c *http.Cookie, instructions string) studio.Photoshoot {
	t.Helper()
	p := createProduct(t, h, c, `{"name":"Jeans","sku":"J-`+strconv.FormatInt(time.Now().UnixNano(), 36)+`"}`)
	if rec := uploadProduct(t, h, c, p.ID, "front", "f.png", fixture(t, "plain.png")); rec.Code != http.StatusCreated {
		t.Fatalf("upload: %d", rec.Code)
	}
	m := createModel(t, h, c, `{"name":"Ava"}`)
	if rec := uploadModel(t, h, c, m.ID, "identity", "a.jpg", fixture(t, "rot6.jpg")); rec.Code != http.StatusCreated {
		t.Fatalf("upload model: %d", rec.Code)
	}
	body := `{"productId":` + strconv.FormatInt(p.ID, 10) + `,"modelId":` + strconv.FormatInt(m.ID, 10) +
		`,"customInstructions":` + strconv.Quote(instructions) + `}`
	rec := doBody(t, h, http.MethodPost, "/api/v1/photoshoots", body, c)
	if rec.Code != http.StatusCreated {
		t.Fatalf("create photoshoot: %d %s", rec.Code, rec.Body)
	}
	return decode[studio.Photoshoot](t, rec)
}

func waitGeneration(t *testing.T, h http.Handler, c *http.Cookie, id int64, status string) studio.Generation {
	t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for {
		g := decode[studio.Generation](t, do(t, h, http.MethodGet, "/api/v1/generations/"+strconv.FormatInt(id, 10), c))
		if g.Status == status {
			return g
		}
		if time.Now().After(deadline) {
			t.Fatalf("generation stuck in %s, want %s", g.Status, status)
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func TestGenerationFlow(t *testing.T) {
	h := newServerT(t, fakeDB{}, webFS)
	c := login(t, h)
	ps := shootFixture(t, h, c, "")
	base := "/api/v1/photoshoots/" + strconv.FormatInt(ps.ID, 10)

	rec := doBody(t, h, http.MethodPost, base+"/generations", `{"recipe":"reference","provider":"fake","variations":2}`, c)
	if rec.Code != http.StatusAccepted || rec.Header().Get("Location") == "" {
		t.Fatalf("start: %d %s", rec.Code, rec.Body)
	}
	g := decode[studio.Generation](t, rec)
	if g.Status != "queued" {
		t.Fatalf("not queued: %s", g.Status)
	}

	g = waitGeneration(t, h, c, g.ID, "succeeded")
	if len(g.Images) != 2 || len(g.Steps) != 2 || g.Settings.Recipe != "reference" {
		t.Fatalf("done: %+v", g)
	}

	// The photoshoot lists its generations; images are filterable.
	got := decode[studio.Photoshoot](t, do(t, h, http.MethodGet, base, c))
	if len(got.Generations) != 1 || got.GenerationCount != 1 || got.LatestImageHash == "" {
		t.Fatalf("photoshoot: %+v", got)
	}
	for _, q := range []string{"?photoshootId=" + strconv.FormatInt(ps.ID, 10), "?productId=" + strconv.FormatInt(ps.ProductID, 10), "?status=pending", ""} {
		list := decode[ImageList](t, do(t, h, http.MethodGet, "/api/v1/images"+q, c))
		if len(list.Items) != 2 {
			t.Errorf("images%s: %d", q, len(list.Items))
		}
	}
	if list := decode[ImageList](t, do(t, h, http.MethodGet, "/api/v1/images?status=approved", c)); len(list.Items) != 0 {
		t.Errorf("approved: %d", len(list.Items))
	}
	if rec := do(t, h, http.MethodGet, "/api/v1/images?status=bogus", c); rec.Code != http.StatusUnprocessableEntity {
		t.Errorf("bad status filter: %d", rec.Code)
	}

	detail := decode[studio.ImageDetail](t, do(t, h, http.MethodGet, "/api/v1/images/"+strconv.FormatInt(g.Images[0].ID, 10), c))
	if detail.Settings.Product.Name != "Jeans" || detail.Prompt == "" || len(detail.Steps) != 1 || detail.Steps[0].ProviderModel == "" {
		t.Fatalf("detail: %+v", detail)
	}
	// Generated bytes are served like any blob.
	if rec := do(t, h, http.MethodGet, "/api/v1/blobs/"+detail.Hash+"?w=256", c); rec.Code != http.StatusOK {
		t.Fatalf("thumbnail: %d", rec.Code)
	}

	// Finished generations cannot be cancelled; used photoshoots cannot be deleted.
	if rec := do(t, h, http.MethodPost, "/api/v1/generations/"+strconv.FormatInt(g.ID, 10)+"/cancel", c); rec.Code != http.StatusConflict {
		t.Errorf("cancel finished: %d", rec.Code)
	}
	if rec := do(t, h, http.MethodDelete, base, c); rec.Code != http.StatusConflict {
		t.Errorf("delete used photoshoot: %d", rec.Code)
	}

	// The model it used can no longer be hard-deleted.
	rec = do(t, h, http.MethodDelete, "/api/v1/models/"+strconv.FormatInt(ps.ModelID, 10), c)
	if rec.Code != http.StatusOK || !decode[catalog.Model](t, rec).Archived {
		t.Errorf("delete used model: %d %s", rec.Code, rec.Body)
	}
}

func TestGenerationFailureAndValidation(t *testing.T) {
	h := newServerT(t, fakeDB{}, webFS)
	c := login(t, h)
	ps := shootFixture(t, h, c, "[fake:fail]")
	base := "/api/v1/photoshoots/" + strconv.FormatInt(ps.ID, 10)

	for _, body := range []string{
		`{"recipe":"reference","provider":"fake","variations":5}`,
		`{"recipe":"nope","provider":"fake","variations":1}`,
		`{"recipe":"reference","provider":"nope","variations":1}`,
	} {
		if rec := doBody(t, h, http.MethodPost, base+"/generations", body, c); rec.Code != http.StatusUnprocessableEntity {
			t.Errorf("%s: %d", body, rec.Code)
		}
	}

	rec := doBody(t, h, http.MethodPost, base+"/generations", `{"recipe":"tryon","provider":"fake","variations":1}`, c)
	g := waitGeneration(t, h, c, decode[studio.Generation](t, rec).ID, "failed")
	if !strings.Contains(g.Error, "simulated") || g.Steps[0].Status != "failed" {
		t.Fatalf("failure: %+v", g)
	}
}

